package com.example.transaction_management.mapper;

import com.example.transaction_management.dto.request.RegisterRequest;
import com.example.transaction_management.dto.response.UserResponse;
import com.example.transaction_management.entity.UserEntity;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;

@Mapper(componentModel = "spring")
public interface UserMapper {

    UserResponse toResponse(UserEntity user);

    @Mapping(target = "id", ignore = true)          // generated by @PrefixedId
    @Mapping(target = "password", ignore = true)    // hashed in the service
    @Mapping(target = "role", ignore = true)        // always set in the service
    @Mapping(target = "createdAt", ignore = true)   // set by @PrePersist
    UserEntity toEntity(RegisterRequest request);
}
